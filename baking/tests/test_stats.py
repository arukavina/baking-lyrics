"""
GET /api/v1/general/stats on empty tables and on seeded data.

The seeded tables hold 1 artist (id 1) with 6 generated songs and no shares.
"""

# Libs
import pytest

# Own
from baking.tests.conftest import add_artists, install_fake_model

STATS = '/api/v1/general/stats'


@pytest.fixture
def empty_client(aws, make_app):
    return make_app().test_client()


def add_artist(repository, name, clean_name, generated):
    """Adds an artist with `generated` generated songs and returns its id."""
    [artist_id] = add_artists(repository, 1, names=[(name, clean_name)])
    for i in range(generated):
        repository.create_generated_song(f'{name} {i}', 'la la la', 'Dummy', artist_id)
    return artist_id


def test_stats_empty_tables(empty_client):
    response = empty_client.get(STATS)

    assert response.status_code == 200
    assert response.json == {'artists': 0, 'songs_generated': 0, 'shares': 0, 'top_artists': []}


def test_stats_seeded(client):
    response = client.get(STATS)

    assert response.status_code == 200
    assert response.json == {
        'artists': 1,
        'songs_generated': 6,
        'shares': 0,
        'top_artists': [{'id': 1, 'name': 'Beyonce Knowles', 'songs_generated': 6}],
    }


def test_stats_counts_shares(client):
    for song_id, network in [(1, 'facebook'), (1, 'twitter'), (2, 'whatsapp')]:
        assert client.post(f'/api/v1/artificial_songs/{song_id}/shares', json={'network': network}).status_code == 201

    assert client.get(STATS).json['shares'] == 3


def test_stats_top_artists_ordering_and_limit(app_repo, client):
    many = add_artist(app_repo, 'many', 'Many', 9)
    beta = add_artist(app_repo, 'beta', 'Beta', 2)
    alpha = add_artist(app_repo, 'zeta raw', 'Alpha', 2)  # tie with beta, sorted by (clean) name
    add_artist(app_repo, 'one', 'One', 1)  # fourth place: cut by the limit
    add_artist(app_repo, 'none', 'None', 0)  # no generated songs: never listed

    response = client.get(STATS)

    assert response.status_code == 200
    assert response.json['artists'] == 6
    assert response.json['songs_generated'] == 6 + 9 + 2 + 2 + 1
    assert [artist['id'] for artist in response.json['top_artists']] == [many, 1, alpha]
    assert response.json['top_artists'][0] == {'id': many, 'name': 'Many', 'songs_generated': 9}
    assert response.json['top_artists'][2] == {'id': alpha, 'name': 'Alpha', 'songs_generated': 2}
    assert beta not in [artist['id'] for artist in response.json['top_artists']]


def test_stats_name_falls_back_to_raw_name(aws, make_app):
    from baking.main.repository import EXTENSION_KEY

    app = make_app()
    repository = app.extensions[EXTENSION_KEY]
    repository.save_catalog(genres=[{'id': 1, 'name': 'Rock'}])
    no_clean = add_artist(repository, 'raw name', None, 1)
    empty_clean = add_artist(repository, 'other raw', '', 1)

    top = app.test_client().get(STATS).json['top_artists']

    assert top == [
        {'id': empty_clean, 'name': 'other raw', 'songs_generated': 1},
        {'id': no_clean, 'name': 'raw name', 'songs_generated': 1},
    ]


def test_stats_count_songs_generated_through_the_api(app, client):
    """Songs generated by the API (models available) bump the counters used by the stats."""
    install_fake_model(app)

    response = client.get('/api/v1/artificial_songs/generate/en/seed/hello/words/10/artist/1/')

    assert response.status_code == 200
    stats = client.get(STATS).json
    assert stats['songs_generated'] == 7
    assert stats['top_artists'] == [{'id': 1, 'name': 'Beyonce Knowles', 'songs_generated': 7}]


def test_stats_read_counters_not_generated_songs(app_repo, client, monkeypatch):
    """The stats never list the generated songs: only the counters table is read."""
    def fail(*args, **kwargs):
        raise AssertionError('generated songs must not be read for the stats')

    app_repo.list_artists()  # warm the artist cache, so no index query is needed below
    monkeypatch.setattr(app_repo, 'list_generated_songs', fail)
    monkeypatch.setattr(app_repo, 'get_generated_song', fail)
    monkeypatch.setattr(app_repo, '_entities', fail)

    assert client.get(STATS).status_code == 200
